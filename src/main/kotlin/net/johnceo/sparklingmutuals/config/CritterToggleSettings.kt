    fun apply(toggles: MutableMap<String, Boolean>): Boolean {
        var changed = false
        javaClass.fields.forEach { field ->
            val name = field.getAnnotation(ConfigOption::class.java)?.name ?: return@forEach
            val enabled = field.getBoolean(this)
            if (toggles.put(name, enabled) != enabled) changed = true
        }
        return changed
    }
